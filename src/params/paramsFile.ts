// Human-readable "key: value" parameter record, included in every tool's download
// list — so the exact inputs used to generate a job are recorded in the zip itself,
// not left to a separate notepad. Re-uploadable in the same tool to restore those
// settings (see each tool's own paramsFile.ts for the field list and type coercion,
// since the actual param shape differs per tool).

export interface ParamField {
  label: string;
  value: string | number | boolean;
}

export function serializeParamsFile(toolName: string, fields: ParamField[]): string {
  const header =
    `# ${toolName} parameters — generated by Reuleaux Web.\n` +
    `# Re-upload this file in the ${toolName} tool to restore these settings.\n\n`;
  const lines = fields.map(({ label, value }) => `${label}: ${value}`);
  return header + lines.join("\n") + "\n";
}

/** Parses "label: value" lines into a flat string map — blank lines and lines
 * starting with "#" (the header) are skipped. Values are returned as raw strings;
 * each tool's own paramsFile.ts converts them to the right type per field. */
export function parseParamsFile(text: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf(":");
    if (idx === -1) continue;
    const label = trimmed.slice(0, idx).trim();
    const value = trimmed.slice(idx + 1).trim();
    if (label) result[label] = value;
  }
  return result;
}
