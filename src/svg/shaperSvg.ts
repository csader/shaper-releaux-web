// Assembles a Shaper-Origin-ready SVG document: the shaper: namespace and per-path
// styling matching the readme's documented convention (black/black = outside cut,
// black/white = inside cut, grey/grey = pocket cut, blue/none = guide).

export type CutType = "outside" | "inside" | "pocket" | "guide" | "online";

export interface CutPath {
  id: string;
  d: string;
  cutType: CutType;
  cutDepthMm: number;
  toolDiaMm?: number;
}

export interface ShaperSvgOptions {
  /** Overall bounding box size in mm (outer dimension + bit clearance each side). */
  boundingWidthMm: number;
  boundingHeightMm: number;
  /** Top-left of the bounding box, typically (-bitSize, -bitSize). */
  originX: number;
  originY: number;
  paths: CutPath[];
  /** Free-text key/value pairs echoed as XML comments (the input parameters). */
  comments: Record<string, string | number>;
  docName: string;
  /** `d` string for a Shaper Origin custom anchor marker (see svg/anchor.ts), if enabled. */
  anchorPathData?: string;
  /** The original app always includes a blue, zero-width-stroke guide rect spanning
   * the bounding box. Off by default here; on for original-app fidelity. */
  includeBoundingBox?: boolean;
}

const STYLE_BY_CUT_TYPE: Record<CutType, string> = {
  outside: "fill:#000000;stroke:#000000;stroke-width:0;stroke-dasharray:none",
  inside: "fill:#ffffff;stroke:#000000;stroke-width:0;stroke-dasharray:none",
  pocket: "fill:#808080;stroke:#808080;stroke-width:0;stroke-dasharray:none",
  guide: "fill:none;stroke:#0000ff;stroke-width:0;stroke-dasharray:none",
  online: "fill:none;stroke:#808080;stroke-width:0;stroke-dasharray:none",
};

function escapeXml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function buildShaperSvg(opts: ShaperSvgOptions): string {
  const {
    boundingWidthMm,
    boundingHeightMm,
    originX,
    originY,
    paths,
    comments,
    docName,
    anchorPathData,
    includeBoundingBox,
  } = opts;

  const commentLines = Object.entries(comments)
    .map(([k, v]) => `<!-- ${escapeXml(k)} = ${escapeXml(String(v))} -->`)
    .join("\n");

  const boundingBoxElement = includeBoundingBox
    ? `    <rect id="boundingbox" style="fill:none;stroke:#0000ff;stroke-width:0;stroke-dasharray:none"
       width="${boundingWidthMm}" height="${boundingHeightMm}" x="${originX}" y="${originY}" />\n`
    : "";

  const pathElements = paths
    .map((p) => {
      const toolAttr = p.toolDiaMm !== undefined ? ` shaper:toolDia="${p.toolDiaMm}mm"` : "";
      return (
        `    <path id="${escapeXml(p.id)}" style="opacity:0.25;${STYLE_BY_CUT_TYPE[p.cutType]}" ` +
        `d="${p.d}" shaper:cutDepth="${p.cutDepthMm}mm"${toolAttr} />`
      );
    })
    .join("\n");

  const anchorElement = anchorPathData
    ? `\n    <path id="anchor-marker" style="fill:#ff0000;stroke:none" d="${anchorPathData}" />`
    : "";

  return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!-- Generated by Reuleaux Web -->
${commentLines}
<svg
   width="${boundingWidthMm}mm"
   height="${boundingHeightMm}mm"
   viewBox="${originX} ${originY} ${boundingWidthMm} ${boundingHeightMm}"
   version="1.1"
   id="${escapeXml(docName)}"
   xmlns="http://www.w3.org/2000/svg"
   xmlns:svg="http://www.w3.org/2000/svg"
   xmlns:shaper="http://www.shapertools.com/namespaces/shaper">
  <g id="layer1">
${boundingBoxElement}${pathElements}${anchorElement}
  </g>
</svg>
`;
}
